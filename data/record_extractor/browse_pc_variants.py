#!/usr/bin/env python3
"""
Browse the FRONT point-cloud variants generated by run_pc_variants.sh.

Opens ALL config windows SIMULTANEOUSLY (one OS window per conf/tex config,
labeled in the title bar). Each window is independently navigable with the
arrow keys. Point clouds show their real RGB color.

Each config runs in its own process (Open3D's run() blocks, so one window
per process is the clean way to have them all live at once).

    <episode>/pc_variants/c<CONF>_t<TEX>/frame_XXXX.npy   (N,6 = xyz+rgb)

Controls (each window):
    N / Right -> next frame     P / Left -> prev frame
    Q / Esc   -> close that window

Example:
    python3 data/record_extractor/browse_pc_variants.py \
        --episode /root/ros2_ws/data/episodes/external/test_collection_small/episode_000_success
"""

import os
import glob
import argparse
import multiprocessing as mp
import numpy as np


def _browse_config_proc(variants_dir, config, n_frames):
    """Run in its own process: one window for one config."""
    import open3d as o3d

    cache = {}

    def load(frame):
        if frame not in cache:
            path = os.path.join(variants_dir, config, f"frame_{frame:04d}.npy")
            cache[frame] = np.load(path) if os.path.exists(path) else None
        return cache[frame]

    def to_o3d(pc_np):
        pcd = o3d.geometry.PointCloud()
        pcd.points = o3d.utility.Vector3dVector(pc_np[:, :3])
        if pc_np.shape[1] >= 6:
            pcd.colors = o3d.utility.Vector3dVector(pc_np[:, 3:6])
        return pcd

    state = {"cur": 0}

    def refresh(vis):
        vis.clear_geometries()
        vis.add_geometry(
            o3d.geometry.TriangleMesh.create_coordinate_frame(size=0.3),
            reset_bounding_box=False)
        pc = load(state["cur"])
        if pc is not None and len(pc) > 0:
            vis.add_geometry(to_o3d(pc), reset_bounding_box=False)
        print(f"[{config}] frame {state['cur']+1}/{n_frames}")

    def nxt(vis):
        if state["cur"] < n_frames - 1:
            state["cur"] += 1
            refresh(vis)
        return False

    def prv(vis):
        if state["cur"] > 0:
            state["cur"] -= 1
            refresh(vis)
        return False

    vis = o3d.visualization.VisualizerWithKeyCallback()
    vis.create_window(window_name=f"PC variant: {config}",
                      width=900, height=700)
    opt = vis.get_render_option()
    opt.background_color = np.asarray([0.1, 0.1, 0.1])
    opt.point_size = 3.0
    vis.register_key_callback(ord("N"), nxt)
    vis.register_key_callback(ord("P"), prv)
    vis.register_key_callback(262, nxt)   # Right arrow
    vis.register_key_callback(263, prv)   # Left arrow

    pc0 = load(0)
    vis.add_geometry(o3d.geometry.TriangleMesh.create_coordinate_frame(size=0.3))
    if pc0 is not None and len(pc0) > 0:
        vis.add_geometry(to_o3d(pc0))
    refresh(vis)
    vis.run()
    vis.destroy_window()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--episode', required=True)
    ap.add_argument('--only', default=None,
                    help='Comma list of configs to show (e.g. c100_t70,c70_t100). '
                         'Default: all.')
    args = ap.parse_args()

    variants_dir = os.path.join(args.episode, "pc_variants")
    if not os.path.isdir(variants_dir):
        raise SystemExit(f"No pc_variants/ in {args.episode}. Run the .sh first.")

    configs = sorted(
        d for d in os.listdir(variants_dir)
        if os.path.isdir(os.path.join(variants_dir, d)))
    if args.only:
        wanted = {c.strip() for c in args.only.split(',')}
        configs = [c for c in configs if c in wanted]
    if not configs:
        raise SystemExit("No config folders found.")

    print(f"Opening {len(configs)} windows: {configs}")
    print("Each window: N/-> next | P/<- prev | Q close")

    procs = []
    for config in configs:
        n = len(glob.glob(os.path.join(variants_dir, config, "*.npy")))
        if n == 0:
            print(f"[{config}] no frames, skipping")
            continue
        p = mp.Process(target=_browse_config_proc,
                       args=(variants_dir, config, n))
        p.start()
        procs.append(p)

    for p in procs:
        p.join()

    print("All windows closed.")


if __name__ == '__main__':
    mp.set_start_method('spawn')
    main()