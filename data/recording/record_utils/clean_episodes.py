#!/usr/bin/env python3
"""
Remove extraction OUTPUTS from episode directories, keeping everything the
recorder produced so the episode can always be re-extracted.

Kept (recorder output = irreplaceable):
    recording.svo2            ZED video + ingested robot_state
    realsense_bag/            wrist colour/depth rosbag
    wrist_camera_topics.json  which topics the bag holds; read by the
                              extractor and qa_report to sync correctly
    qos_overrides.yaml        bag QoS profile, written alongside the bag
    labels.json               recording-plan labels + operator outcome

Everything else (front_rgb/, front_pc/, wrist_rgb/, wrist_pc/, state.npy,
force.npy, frame_timestamps_ns.npy, sync_gaps.npy, qa_*, sync_histogram_*,
trim_applied.json, ...) is regenerated by extract_episodes.py.

Usage:
    # Dry run (default) — only prints what would be deleted
    python clean_episodes.py

    # Actually delete
    python clean_episodes.py --execute

Environment:
    FOLDER_NAME  — dataset folder name (default: foil_lifting_collection)
    WORKDIR      — workspace root (default: /ros2_ws/data)
"""

import os
import sys
import shutil
import argparse

FOLDER_NAME = os.environ.get("FOLDER_NAME", "foil_lifting_collection_tesollo_bottom")
WORKDIR = os.environ.get("WORKDIR", "/root/ros2_ws/data")

# Recorder output only. These cannot be regenerated: the SVO and bag are the
# raw recordings, and the two sidecars describe how to read the bag. Deleting
# wrist_camera_topics.json in particular makes the extractor fall back to a
# hardcoded topic name, which fails silently if the real topic differs.
KEEP = {
    "recording.svo2",
    "realsense_bag",
    "wrist_camera_topics.json",
    "qos_overrides.yaml",
    # Plan labels and the operator's outcome answers. Not derivable from
    # anything on disk: the plan slot is only known at recording time, and the
    # three outcome questions were answered by a human who has since gone
    # home. Deleting this is the one thing in an episode that re-extraction
    # cannot repair, and it also stores which slots count as done.
    "labels.json",
}


def collect_deletions(root_dir: str) -> list[str]:
    """Walk episode directories and collect paths to delete."""
    deletions: list[str] = []

    if not os.path.isdir(root_dir):
        print(f"ERROR: root directory does not exist: {root_dir}", file=sys.stderr)
        sys.exit(1)

    for entry in sorted(os.listdir(root_dir)):
        episode_path = os.path.join(root_dir, entry)

        # Only process episode_* directories
        if not os.path.isdir(episode_path) or not entry.startswith("episode_"):
            continue

        for item in sorted(os.listdir(episode_path)):
            if item in KEEP:
                continue
            deletions.append(os.path.join(episode_path, item))

    return deletions


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--execute",
        action="store_true",
        help="Actually perform deletions. Without this flag, only a dry-run is shown.",
    )
    args = parser.parse_args()

    rec_dir = os.path.join(WORKDIR, f"recording/episodes/external/{FOLDER_NAME}")
    root_dir = rec_dir if os.path.exists(rec_dir) else os.path.join(WORKDIR, f"episodes/external/{FOLDER_NAME}")
    print(f"Dataset root : {root_dir}")
    print(f"Keeping      : {KEEP}")
    print(f"Mode         : {'🔴 EXECUTE' if args.execute else '🟡 DRY RUN'}")
    print("-" * 60)

    deletions = collect_deletions(root_dir)

    if not deletions:
        print("Nothing to delete — all episodes are already clean.")
        return

    total_size = 0
    for path in deletions:
        if os.path.isdir(path):
            size = sum(
                os.path.getsize(os.path.join(dp, f))
                for dp, _, fnames in os.walk(path)
                for f in fnames
            )
        else:
            size = os.path.getsize(path)
        total_size += size
        tag = "DIR " if os.path.isdir(path) else "FILE"
        print(f"  [{tag}] {path}  ({size / 1024 / 1024:.2f} MB)")

    print("-" * 60)
    print(f"Total items to delete : {len(deletions)}")
    print(f"Total size to free    : {total_size / 1024 / 1024:.1f} MB")
    print("-" * 60)

    if not args.execute:
        print("\n⚠️  Dry run complete. Re-run with --execute to actually delete.")
        return

    # Final confirmation gate
    answer = input("\n⚠️  Type 'yes' to confirm deletion: ").strip().lower()
    if answer != "yes":
        print("Aborted.")
        return

    for path in deletions:
        if os.path.isdir(path):
            shutil.rmtree(path)
        else:
            os.remove(path)
        print(f"  Deleted: {path}")

    print(f"\n✅ Done. Removed {len(deletions)} items.")


if __name__ == "__main__":
    main()